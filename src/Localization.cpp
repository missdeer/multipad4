#include "Localization.h"
#include "resource.h"
namespace {
struct Language { UINT command; LANGID language; };
constexpr Language languages[] = {
    {IDM_LANG_ENGLISH_US, MAKELANGID(LANG_ENGLISH, SUBLANG_ENGLISH_US)},
    {IDM_LANG_CHINESE_SIMPLIFIED, MAKELANGID(LANG_CHINESE, SUBLANG_CHINESE_SIMPLIFIED)},
    {IDM_LANG_CHINESE_TRADITIONAL, MAKELANGID(LANG_CHINESE, SUBLANG_CHINESE_TRADITIONAL)},
    {IDM_LANG_JAPANESE, MAKELANGID(LANG_JAPANESE, SUBLANG_DEFAULT)},
    {IDM_LANG_GERMAN, MAKELANGID(LANG_GERMAN, SUBLANG_DEFAULT)},
    {IDM_LANG_ITALIAN, MAKELANGID(LANG_ITALIAN, SUBLANG_DEFAULT)},
    {IDM_LANG_KOREAN, MAKELANGID(LANG_KOREAN, SUBLANG_DEFAULT)},
    {IDM_LANG_PORTUGUESE_BRAZIL, MAKELANGID(LANG_PORTUGUESE, SUBLANG_PORTUGUESE_BRAZILIAN)},
    {IDM_LANG_FRENCH_FRANCE, MAKELANGID(LANG_FRENCH, SUBLANG_DEFAULT)},
    {IDM_LANG_RUSSIAN, MAKELANGID(LANG_RUSSIAN, SUBLANG_DEFAULT)},
    {IDM_LANG_POLISH, MAKELANGID(LANG_POLISH, SUBLANG_DEFAULT)},
    {IDM_LANG_SLOVENIAN, MAKELANGID(LANG_SLOVENIAN, SUBLANG_DEFAULT)}
};
}
LANGID LanguageForCommand(UINT command) {
    for (const auto& item : languages) if (item.command == command) return item.language;
    return GetUserDefaultUILanguage();
}
UINT CommandForLanguage(LANGID language) {
    for (const auto& item : languages) if (item.language == language) return item.command;
    return IDM_LANG_USER_DEFAULT;
}
